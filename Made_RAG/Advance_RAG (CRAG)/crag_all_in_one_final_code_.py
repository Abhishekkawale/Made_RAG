def eval_each_dc_node(state:State) -> state:

  q = state('question')     # fetching ques

  scores: List[float] = []
  reasons: List[str]= []
  good: List[Document] = []    # creating empty lists

  for d in state['docs']:    # loop chala rhe hai
    out = doc_eval_chain.invoke({"question":q, "chunk":d.page_content})   # provind llm a ques and chunk
    scores.append(out.score)
    reasons.append(out.reason)   # and asking it a score ans reason

    # 5) for CORRECT case we will refine only docs with score > LOWER.TH
    if out.score > LOWER_TH:
      good.append(d)

  # 2) CORRECT if atleast one doc > UPPER_TH
  if any(s > UPPER_TH for s in scores):
    return {
        "good_docs":good,
        "verdict":CORRECT,
        "reason":f"At least one retrieved chunk scored > {UPPER_TH}.",
          }

  # 3) INCORRECT if all docs < LOWER_TH
  if len(scores) > 0 and all(s < LOWER_TH for s in scores):
    why = "No chunk is sufficient "
    return {
        "good_docs":[],
        "verdict":INCORRECT,
        "reason":f"All retrieved chunk scored < {LOWER_TH}. {why}",
          }

  # 4) Anything inbetween => AMBIGUOUS
  why = "Mixed relevence signals."
  return {
      "good_docs":[],
      "verdict":AMBIGUOUS,
      "reason":f"No chunk scored > {UPPER_TH}, but not all were < {LOWER_TH}. {why}",
        }

